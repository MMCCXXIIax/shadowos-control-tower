-- Persistent creator intelligence: evidence ledger and qualification screening.
create table if not exists public.shadowos_creator_evidence (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  evidence_type text not null check (evidence_type in ('profile','content','audience','buying_signal','offer','risk','note')),
  title text not null,
  source_url text,
  summary text not null,
  signal text check (signal in ('positive','neutral','negative','unknown')) default 'unknown',
  confidence text not null default 'medium' check (confidence in ('high','medium','low','unknown')),
  captured_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);
create table if not exists public.shadowos_creator_screenings (
  creator_id text primary key references public.shadowos_creators(creator_id) on delete cascade,
  audience_fit integer not null default 0 check (audience_fit between 0 and 25),
  buying_signals integer not null default 0 check (buying_signals between 0 and 25),
  expertise_authority integer not null default 0 check (expertise_authority between 0 and 25),
  partnership_readiness integer not null default 0 check (partnership_readiness between 0 and 25),
  decision text not null default 'in_review' check (decision in ('in_review','qualified','hold','reject')),
  rationale text,
  screened_at timestamptz,
  updated_at timestamptz not null default now()
);
