-- Creator-specific marketing plans and approval-gated content calendar items.
create table if not exists public.shadowos_marketing_plans (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  product_brief_id bigint references public.shadowos_product_briefs(id) on delete set null,
  campaign_name text not null,
  audience_segment text not null,
  positioning text not null,
  offer_angle text not null,
  voice_notes text,
  pre_launch_strategy text not null,
  post_launch_strategy text not null,
  asset_checklist text,
  status text not null default 'draft',
  reviewed_at timestamptz,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.shadowos_marketing_items (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  plan_id bigint references public.shadowos_marketing_plans(id) on delete cascade,
  product_brief_id bigint references public.shadowos_product_briefs(id) on delete set null,
  phase text not null,
  channel text not null,
  content_type text not null,
  title text not null,
  objective text not null,
  hook text,
  body text,
  call_to_action text,
  asset_direction text,
  scheduled_for timestamptz,
  status text not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
