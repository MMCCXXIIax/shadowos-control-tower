create table if not exists public.shadowos_whop_products (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  product_brief_id bigint references public.shadowos_product_briefs(id) on delete set null,
  whop_product_id text,
  product_name text not null,
  status text not null default 'planned',
  currency text not null default 'USD',
  last_synced_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.shadowos_revenue_share_terms (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  whop_product_id bigint not null references public.shadowos_whop_products(id) on delete cascade,
  creator_share_percent numeric(5,2) not null,
  shadow_share_percent numeric(5,2) not null,
  negotiated boolean not null default false,
  effective_at timestamptz not null default now(),
  status text not null default 'draft',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.shadowos_whop_transactions (
  id bigint generated by default as identity primary key,
  whop_payment_id text unique,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  whop_product_id bigint references public.shadowos_whop_products(id) on delete set null,
  gross_amount_cents bigint not null default 0,
  whop_fees_cents bigint not null default 0,
  refunds_cents bigint not null default 0,
  net_amount_cents bigint not null default 0,
  creator_share_cents bigint not null default 0,
  shadow_share_cents bigint not null default 0,
  currency text not null default 'USD',
  payment_status text not null default 'paid',
  paid_at timestamptz,
  source text not null default 'manual',
  imported_at timestamptz not null default now()
);
