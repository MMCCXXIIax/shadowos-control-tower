-- Applied to the connected ShadowOS Supabase project bklrfjnqbyyntlhmprkp.
-- Outreach is approval-gated. Drafting does not send messages; send state is recorded manually after human approval.
create table if not exists public.shadowos_outreach_drafts (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  channel text not null check (channel in ('instagram','email')),
  subject text,
  body text not null,
  personalization_summary text,
  status text not null default 'draft' check (status in ('draft','needs_review','approved','sent','replied','rejected','archived')),
  approved_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create table if not exists public.shadowos_outreach_events (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  draft_id bigint references public.shadowos_outreach_drafts(id) on delete set null,
  channel text not null check (channel in ('instagram','email')),
  event_type text not null,
  note text,
  occurred_at timestamptz not null default now()
);
create table if not exists public.shadowos_followups (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  draft_id bigint references public.shadowos_outreach_drafts(id) on delete set null,
  channel text not null check (channel in ('instagram','email')),
  due_at timestamptz not null,
  status text not null default 'scheduled',
  note text,
  created_at timestamptz not null default now()
);
-- RLS policies were applied with the Supabase migration tool; the app uses the publishable key.
