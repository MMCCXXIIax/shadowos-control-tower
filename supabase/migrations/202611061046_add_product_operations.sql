-- Product Operations stores creator-specific architecture briefs and production review reports.
create table if not exists public.shadowos_product_briefs (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.shadowos_creators(creator_id) on delete cascade,
  hypothesis_number integer not null check (hypothesis_number between 1 and 4),
  product_name text not null,
  audience_problem text not null,
  buying_signal text,
  transformation text not null,
  format text not null,
  outline text not null,
  asset_requirements text,
  visual_direction text,
  launch_notes text,
  status text not null default 'hypothesis',
  production_report text,
  review_notes text,
  reviewed_at timestamptz,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (creator_id, hypothesis_number)
);
